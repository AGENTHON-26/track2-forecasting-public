_SETS = {k: set(v) for k, v in CAL.items()}

#: step multiplier by asset class and event effect; keys: FOMC = decision date, FOMC_next = the next
#: business day, ECB / BoJ = decision date. Absent = 1.0.
DEFAULT_TABLE: dict[str, dict[str, float]] = {
    # half-strength table: the only variant whose week-block 95% CI excludes 0 in BOTH 2003-19 and 2020-24
    "rates": {"FOMC": 1.1, "FOMC_next": 1.1},
    "fx": {"FOMC_next": 1.3, "ECB": 1.12, "BoJ": 1.05},
}
#: the full-strength table the first backtest used (CI includes 0 in 2020-24): kept for comparison only.
FULL_TABLE: dict[str, dict[str, float]] = {
    "rates": {"FOMC": 1.2, "FOMC_next": 1.2},
    "fx": {"FOMC_next": 1.6, "ECB": 1.25, "BoJ": 1.1},
}
CLIP = (1.0, 1.7)


def step_mult(cls: str, date: str, table=None) -> float:
    t = (table or DEFAULT_TABLE).get(cls, {})
    d = pd.Timestamp(date)
    prev = str((d - pd.offsets.BDay(1)).date())
    m = 1.0
    for key, hit in (("FOMC", date in _SETS["FOMC"]), ("FOMC_next", prev in _SETS["FOMC"]),
                     ("ECB", date in _SETS["ECB"]), ("BoJ", date in _SETS["BoJ"])):
        if hit and key in t:
            m = max(m, t[key])
    m = float(min(max(m, CLIP[0]), CLIP[1]))
    dow = t.get("dow")                      # optional {weekday: multiplier}, applied after the event clip
    if dow:
        m *= float(dow.get(d.dayofweek, 1.0))
    return m


def horizon_scale(cls: str, step_dates: list[str], table=None) -> list[float]:
    """For horizons 1..len(step_dates): sqrt(mean of squared step multipliers up to h)."""
    ms = np.array([step_mult(cls, d, table) for d in step_dates])
    return [float(np.sqrt(np.mean(ms[:h] ** 2))) for h in range(1, len(ms) + 1)]


def future_bdays(asof: str, n: int) -> list[str]:
    return [str((pd.Timestamp(asof) + pd.offsets.BDay(k)).date()) for k in range(1, n + 1)]
